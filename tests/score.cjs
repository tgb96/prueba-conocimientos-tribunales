const fs = require('fs'), path = require('path'), vm = require('vm'), assert = require('assert/strict');
const repo = path.resolve(__dirname, '..');
const saved = new Map();
const context = vm.createContext({ document: { addEventListener() {} }, localStorage: { getItem: key => saved.get(key) || null, setItem: (key, value) => saved.set(key, value) } });
vm.runInContext(fs.readFileSync(path.join(repo, 'app.js'), 'utf8'), context);
const bank = JSON.parse(fs.readFileSync(path.join(repo, 'banco_B400.json'), 'utf8'));
const cases = [[0, 1], [1, 1], [2, 1], [3, 2], [6, 4], [9, 6], [15, 10], [21, 14], [23, 15], [24, 16], [25, 17], [27, 18], [29, 19], [30, 20]];
for (const [correct, expected] of cases) assert.equal(context.calculateScore20(correct, 30), expected);
let previous = 0;
context.fixture = bank.items.slice(0, 30);
for (let correct = 0; correct <= 30; correct++) {
  context.correctCount = correct;
  vm.runInContext('state.attempt=fixture;state.answers={};state.elapsed=42;fixture.forEach((q,i)=>state.answers[q.bank_id]=i<correctCount?q.key:(q.key+1)%5);', context);
  const result = context.calculateResult(false);
  assert.equal(result.correct, correct);
  assert.equal(result.wrong, 30 - correct);
  assert.equal(result.omitted, 0);
  assert.equal(result.total, 30);
  assert.ok(result.score20 >= 1 && result.score20 <= 20 && result.score20 >= previous);
  previous = result.score20;
  assert.ok(Number.isInteger(result.score20));
  assert.match(context.formatScore20(result.score20), /^\d+$/, 'Puntaje sin decimales');
}
assert.equal(context.formatScore20(19.33), '19', 'Redondear también los puntajes del historial anterior');
assert.equal(context.formatScore20(14.49), '14');
assert.equal(context.formatScore20(14.5), '15', 'Desde ,5 se aproxima hacia arriba');
assert.equal(context.formatScore20(20), '20');
vm.runInContext('state.answers={};fixture.slice(0,15).forEach(q=>state.answers[q.bank_id]=q.key);fixture.slice(15,20).forEach(q=>state.answers[q.bank_id]=(q.key+1)%5);', context);
const mixed = context.calculateResult(true);
assert.equal(mixed.score20, 10); assert.equal(mixed.wrong, 5); assert.equal(mixed.omitted, 10); assert.equal(mixed.auto, true);
context.saveHistory(mixed);
assert.equal(JSON.parse(saved.get('b500-history'))[0].score20, 10);
vm.runInContext('state.answers={};', context);
const omitted = context.calculateResult(true);
assert.equal(omitted.score20, 1); assert.equal(omitted.omitted, 30);
context.fixture = bank.items.slice(0, 10);
vm.runInContext('state.attempt=fixture;state.answers={};fixture.forEach(q=>state.answers[q.bank_id]=q.key);', context);
const quick = context.calculateResult(false);
assert.equal(quick.total, 10); assert.equal(quick.correct, 10); assert.equal(quick.score20, null);
const report = { version: '20261026-puntaje-entero', scale: 'Proporcional: aciertos × 20 ÷ 30, mínimo 1 y máximo 20; entero más cercano, desde ,5 hacia arriba.', full_results_checked: 31, checkpoints: cases, mixed_wrong_and_omitted: true, automatic_finish: true, history_score_saved: true, quick_attempt_unchanged: true, decimals: false, legacy_scores_rounded: true, half_rounded_up: true };
fs.writeFileSync(path.join(repo, 'VALIDACION_PUNTAJE.json'), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report, null, 2));
